export function zh(value) {
  return typeof value === "string" ? TEXT[value] || value : value;
}

export function zhStatus(value) {
  const original = String(value || "unknown");
  return STATUS[original.toLowerCase().replaceAll("-", "_")] || original;
}

export function zhPhase(value) {
  if (typeof value === "string" && value.startsWith("visual:")) {
    return `画面生成 · ${value.slice(7)}`;
  }
  return zhStatus(value);
}
